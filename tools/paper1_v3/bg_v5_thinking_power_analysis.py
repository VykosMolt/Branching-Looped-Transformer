"""V5 Thinking pre-answer power extension -- analysis (SEALED PROTOCOL).

Within-Thinking analysis of the powered replication cohort (hash-pool offsets
>= 1500, generated by bg_v5_thinking_power_generate.py with the sealed v3
Thinking generator protocol unmodified: k=4, max_new=448, T=0.7, top_p=0.95,
seed 20260724, strict pre-answer cut, deterministic split_for splits).

SEALED ENDPOINTS AND VERDICTS (written before any v5 generation):
  Stage A (gate): reproduce the pilot's published increments (both the 4- and
    5-shortcut arms of thinking_preanswer_results.json, and the preserved
    per-candidate held-out scores) to 1e-9 from the preserved pilot artifacts
    BEFORE touching any new data. Abort on any mismatch.
  PRIMARY: new-only cohort (tasks at offsets >= 1500, disjoint from all prior
    slices), incremental AUROC (combined - shortcut) under the adversarial
    5-shortcut composite (incl. malformed-sibling count), fit on new train+val,
    evaluated on new heldout; paired task-clustered bootstrap, 2000 rounds,
    seed 20260727; 95% CI, plus 90% CI for TOST at +/-0.05.
  SECONDARY: pooled with the pilot -- labelled 'pooled precision estimate --
    NOT independent replication'.
  Sealed malformedness controls: (a) drop-tasks-with->=75%-malformed control
    arm on the primary held-out scores; (b) hidden-only malformedness-
    prediction AUROC diagnostic on the new held-out records.
  VERDICT (checked strictly in this order, on the PRIMARY point estimate and
  seed-20260727 intervals):
    NEGATIVE_TRANSFER        if 95% upper < 0
    POSITIVE_REPLICATION     if 95% lower > 0   (flag PRACTICALLY_SMALL=true
                             if point estimate < 0.05 or the equivalence
                             condition also holds)
    PRACTICAL_EQUIVALENCE    if 90% CI entirely within [-0.05, +0.05]
    UNRESOLVED               otherwise (incl. insufficient-data conditions,
                             reported with counts, not massaged)
  No stopping rules, no budget changes: this analysis runs ONCE on whatever
  the generator produced.

Writes thinking_power_results.json (+ raw_predictions_heldout_v5.json) into
artifacts/reports/thinking_preanswer_power_v5_20260727/. Read-only w.r.t. all
prior artifact roots. --stage-a-only runs the gate alone (CPU smoke).
"""
